export const agentRunPrerequisiteIndexes = [
  'gugu_agent_session_owner', 'gugu_agent_message_session', 'gugu_agent_prompt_owner_session',
]

export const agentRunTables = [
  'agent_run_startups', 'agent_run_leases', 'agent_run_checkpoints', 'agent_run_events',
  'agent_run_interaction_receipts', 'agent_run_dispatch',
  'agent_interaction_intents', 'agent_interaction_bindings', 'agent_interaction_resumes',
] as const

const run = 'user_id uuid NOT NULL, session_id integer NOT NULL, run_id varchar(128) NOT NULL'
const ownerFks = `FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY(session_id,user_id) REFERENCES conversation_sessions(id,user_id) ON DELETE CASCADE`
const checkpointFk = `FOREIGN KEY(user_id,session_id,run_id)
  REFERENCES agent_run_checkpoints(user_id,session_id,run_id) ON DELETE CASCADE`
const promptFk = `FOREIGN KEY(prompt_id,user_id,session_id)
  REFERENCES interaction_prompts(id,user_id,session_id) ON DELETE CASCADE`

export const agentRunSql = `
CREATE UNIQUE INDEX gugu_agent_session_owner ON conversation_sessions(id,user_id);
CREATE UNIQUE INDEX gugu_agent_message_session ON conversation_messages(id,session_id);
CREATE UNIQUE INDEX gugu_agent_prompt_owner_session ON interaction_prompts(id,user_id,session_id);

CREATE TABLE agent_run_startups (
  ${run},
  status varchar(16) NOT NULL CHECK (status IN ('pending','failed')),
  created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
  PRIMARY KEY(user_id,session_id,run_id), ${ownerFks}
);
CREATE TABLE agent_run_leases (
  ${run},
  token varchar(64) NOT NULL, fence bigint NOT NULL,
  expires_at timestamptz NOT NULL, created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
  PRIMARY KEY(user_id,session_id), ${ownerFks}
);
CREATE INDEX ix_agent_run_leases_expires_at ON agent_run_leases(expires_at);
CREATE TABLE agent_run_checkpoints (
  ${run},
  version bigint NOT NULL, sequence bigint NOT NULL,
  status varchar(20) NOT NULL, phase varchar(20) NOT NULL,
  nonce bytea NOT NULL, payload bytea NOT NULL,
  created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
  PRIMARY KEY(user_id,session_id,run_id), ${ownerFks}
);
CREATE TABLE agent_run_events (
  ${run},
  event_id varchar(128) NOT NULL, sequence bigint NOT NULL,
  nonce bytea NOT NULL, payload bytea NOT NULL, created_at timestamptz NOT NULL, acknowledged_at timestamptz,
  PRIMARY KEY(user_id,session_id,run_id,event_id), UNIQUE(user_id,session_id,run_id,sequence), ${checkpointFk}
);
CREATE INDEX ix_agent_run_events_pending ON agent_run_events(user_id,session_id,run_id,sequence)
  WHERE acknowledged_at IS NULL;
CREATE TABLE agent_run_interaction_receipts (
  ${run},
  receipt text NOT NULL, created_at timestamptz NOT NULL,
  PRIMARY KEY(user_id,session_id,run_id,receipt), ${checkpointFk}
);
CREATE TABLE agent_run_dispatch (
  sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ${run},
  state varchar(16) NOT NULL CHECK(state IN ('queued','selected','done')), message_id integer NOT NULL,
  nonce bytea NOT NULL, payload bytea NOT NULL, request_expires_at timestamptz NOT NULL,
  token varchar(64), fence bigint NOT NULL DEFAULT 0, lease_expires_at timestamptz,
  cancel_requested boolean NOT NULL DEFAULT false, blocked_reason varchar(32),
  UNIQUE(user_id,session_id,run_id), ${ownerFks},
  FOREIGN KEY(message_id,session_id) REFERENCES conversation_messages(id,session_id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uq_agent_dispatch_selected ON agent_run_dispatch(user_id,session_id) WHERE state='selected';
CREATE TABLE agent_interaction_intents (
  ${run},
  interaction_id varchar(200) NOT NULL, tool_call_id varchar(200) NOT NULL,
  ciphertext text NOT NULL, nonce varchar(64) NOT NULL, encrypted_data_key text NOT NULL,
  key_version integer NOT NULL, expires_at timestamptz NOT NULL,
  PRIMARY KEY(user_id,session_id,run_id,interaction_id), ${checkpointFk}
);
CREATE TABLE agent_interaction_bindings (
  ${run}, prompt_id integer PRIMARY KEY,
  interaction_id varchar(200) NOT NULL, tool_call_id varchar(200) NOT NULL,
  UNIQUE(user_id,session_id,run_id,interaction_id), ${checkpointFk}, ${promptFk}
);
CREATE TABLE agent_interaction_resumes (
  ${run}, prompt_id integer NOT NULL,
  interaction_id varchar(200) NOT NULL, receipt varchar(200) NOT NULL,
  created_at timestamptz NOT NULL, completed_at timestamptz,
  claim_token varchar(64), claim_expires_at timestamptz,
  PRIMARY KEY(user_id,session_id,run_id,prompt_id), UNIQUE(user_id,session_id,run_id,receipt),
  ${checkpointFk}, ${promptFk}
);`
