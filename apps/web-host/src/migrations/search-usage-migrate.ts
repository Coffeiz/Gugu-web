import type { PoolClient, QueryResultRow } from 'pg'
import { createAgentSchemaMigration } from './agent-schema-migrate.js'

const table = 'search_usage'
const indexUser = 'ix_search_usage_user_id'
const indexCreated = 'ix_search_usage_created_at'

async function canAdoptSearchUsage(client: PoolClient): Promise<boolean> {
  const columns = await client.query<QueryResultRow & {
    name: string
    type: string
    required: boolean
    identity: string
    defaultValue: string | null
  }>(`SELECT a.attname AS name, format_type(a.atttypid,a.atttypmod) AS type, a.attnotnull AS required,
      a.attidentity AS identity, pg_get_expr(d.adbin,d.adrelid) AS "defaultValue"
    FROM pg_attribute a
    JOIN pg_class t ON t.oid=a.attrelid
    JOIN pg_namespace n ON n.oid=t.relnamespace
    LEFT JOIN pg_attrdef d ON (d.adrelid,d.adnum)=(a.attrelid,a.attnum)
    WHERE n.nspname=current_schema() AND t.relname=$1 AND a.attnum>0 AND NOT a.attisdropped
    ORDER BY a.attnum`, [table])
  const expected = [
    ['id', 'integer'], ['user_id', 'uuid'], ['query', 'character varying(500)'], ['created_at', 'timestamp with time zone'],
  ]
  if (columns.rows.length !== expected.length || columns.rows.some((row, index) => {
    const shape = expected[index]
    return !shape || row.name !== shape[0] || row.type !== shape[1] || row.required !== true
      || row.identity !== '' && row.name !== 'id'
  })) return false
  const id = columns.rows[0]
  if (!id || id.identity === '' && !/^nextval\(/u.test(id.defaultValue ?? '')) return false

  const constraints = await client.query<{ kind: string; definition: string; validated: boolean }>(
    `SELECT c.contype AS kind, pg_get_constraintdef(c.oid) AS definition, c.convalidated AS validated
     FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace n ON n.oid=t.relnamespace
     WHERE n.nspname=current_schema() AND t.relname=$1 AND c.contype IN ('p','f')`, [table],
  )
  if (constraints.rows.length !== 2
    || !constraints.rows.some(row => row.kind === 'p' && row.definition === 'PRIMARY KEY (id)' && row.validated)
    || !constraints.rows.some(row => row.kind === 'f'
      && row.definition === 'FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE' && row.validated)) return false

  const indexes = await client.query<{ name: string; definition: string }>(
    `SELECT indexname AS name, indexdef AS definition FROM pg_indexes
     WHERE schemaname=current_schema() AND tablename=$1 AND indexname=ANY($2::text[])`,
    [table, [indexUser, indexCreated]],
  )
  return indexes.rows.every(row => row.name === indexUser
    ? /^CREATE INDEX ix_search_usage_user_id ON .+ USING btree \(user_id\)$/u.test(row.definition)
    : row.name === indexCreated && /^CREATE INDEX ix_search_usage_created_at ON .+ USING btree \(created_at\)$/u.test(row.definition))
}

const sql = `CREATE TABLE IF NOT EXISTS search_usage (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  query varchar(500) NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_search_usage_user_id ON search_usage(user_id);
CREATE INDEX IF NOT EXISTS ix_search_usage_created_at ON search_usage(created_at);`

const migration = createAgentSchemaMigration({
  ledger: 'gugu_node_search_usage_migrations',
  revision: 'search_usage_0001',
  sql,
  tables: [table],
  indexes: [indexUser, indexCreated],
  prerequisites: ['users'],
  adoptExisting: canAdoptSearchUsage,
  lockKey: ':gugu-search-usage-schema',
})

export const checkSearchUsageMigration = migration.check
export const applySearchUsageMigration = migration.apply
