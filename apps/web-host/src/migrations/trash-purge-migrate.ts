import { createAgentSchemaMigration } from './agent-schema-migrate.js'

const sql = `CREATE TABLE trash_purge_jobs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status varchar(16) NOT NULL CHECK (status IN ('queued','running','completed','failed')),
  snapshot_at timestamptz NOT NULL,
  progress_current integer NOT NULL DEFAULT 0 CHECK (progress_current >= 0),
  progress_total integer NOT NULL DEFAULT 0 CHECK (progress_total >= 0),
  failed_count integer NOT NULL DEFAULT 0 CHECK (failed_count >= 0),
  error_code varchar(64),
  lease_owner varchar(128),
  lease_until timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at timestamptz,
  finished_at timestamptz
);
CREATE UNIQUE INDEX uq_trash_purge_jobs_user_active
  ON trash_purge_jobs(user_id) WHERE status IN ('queued','running');
CREATE UNIQUE INDEX uq_trash_purge_jobs_global_running
  ON trash_purge_jobs(status) WHERE status='running';
CREATE INDEX ix_trash_purge_jobs_claim ON trash_purge_jobs(status,lease_until,created_at);`

const migration = createAgentSchemaMigration({
  ledger: 'gugu_node_trash_purge_migrations',
  revision: 'trash_purge_0001',
  sql,
  tables: ['trash_purge_jobs'],
  indexes: ['uq_trash_purge_jobs_user_active', 'uq_trash_purge_jobs_global_running', 'ix_trash_purge_jobs_claim'],
  prerequisites: ['users'],
  lockKey: ':gugu-trash-purge-schema',
})

const agentOperationsMigration = createAgentSchemaMigration({
  ledger: 'gugu_node_trash_purge_agent_migrations',
  revision: 'trash_purge_agent_0001',
  sql: `CREATE TABLE trash_purge_agent_operations (
  operation_id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  job_id integer NOT NULL REFERENCES trash_purge_jobs(id) ON DELETE CASCADE,
  snapshot_digest char(64) NOT NULL,
  file_count integer NOT NULL CHECK (file_count >= 0),
  folder_count integer NOT NULL CHECK (folder_count >= 0),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_trash_purge_agent_operations_user_created
  ON trash_purge_agent_operations(user_id,created_at);`,
  tables: ['trash_purge_agent_operations'],
  indexes: ['ix_trash_purge_agent_operations_user_created'],
  prerequisites: ['users', 'trash_purge_jobs'],
  lockKey: ':gugu-trash-purge-agent-operations-schema',
})

export async function checkTrashPurgeMigration(pool: Parameters<typeof migration.check>[0]) {
  const base = await migration.check(pool)
  if (base !== 'applied') return base
  return agentOperationsMigration.check(pool)
}

export async function applyTrashPurgeMigration(pool: Parameters<typeof migration.apply>[0]) {
  const base = await migration.apply(pool)
  const agentOperations = await agentOperationsMigration.apply(pool)
  return base === 'applied' || agentOperations === 'applied' ? 'applied' as const : 'unchanged' as const
}
