import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { Pool } from 'pg'
import test from 'node:test'
import { createPostgresRuntime } from '@gugu/core/data'
import { createTelegramConnector } from '@gugu/core/im/telegram-connect'
import { createApp } from '../../src/app.js'
import { createUserToken } from '../../src/modules/auth/auth.js'

const databaseUrl = process.env.GUGU_WEBUI_TEST_DATABASE_URL
const ownerA = '11111111-1111-4111-8111-111111111111'
const ownerB = '22222222-2222-4222-8222-222222222222'
const secret = 'synthetic-telegram-connect-host-secret'
const tokenA = '123456:ABCDEFGHIJKLMNOPQRSTUVWXYZabcdef0123456789'
const tokenB = '654321:ABCDEFGHIJKLMNOPQRSTUVWXYZabcdef0123456789'

test('Telegram connect route and Core use PostgreSQL unique locks, owner scope and replacement rollback', {
  skip: !databaseUrl && '需要隔离 PostgreSQL 验证 Telegram 连接事务',
}, async () => {
  const schema = `telegram_connect_${randomUUID().replaceAll('-', '')}`
  const admin = new Pool({ connectionString: databaseUrl, max: 1 })
  await admin.query(`CREATE SCHEMA "${schema}"`)
  const pool = new Pool({ connectionString: databaseUrl, options: `-c search_path=${schema}`, max: 4 })
  const runtime = await createPostgresRuntime({ url: databaseUrl!, schema })
  const verified: string[] = [], published: string[] = []
  try {
    await pool.query(`
      CREATE TABLE user_bots(
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id uuid NOT NULL,platform text NOT NULL,
        name text NOT NULL,app_id text,app_secret text,enabled boolean NOT NULL,group_chat_enabled boolean NOT NULL,
        bot_platform_user_id text,owner_platform_user_id text,owner_bound_at timestamptz,created_at timestamptz NOT NULL
      );
      CREATE TABLE conversation_sessions(
        id integer PRIMARY KEY,user_id uuid NOT NULL,source text NOT NULL,snapshot_expires_at timestamptz,
        context_epoch integer NOT NULL DEFAULT 0
      );
      INSERT INTO conversation_sessions(id,user_id,source,context_epoch) VALUES
        (1,'${ownerA}','telegram',2),(2,'${ownerA}','web',4),(3,'${ownerB}','telegram',7);
    `)
    const connector = createTelegramConnector(runtime.db, {
      async verify(token) {
        verified.push(token)
        if (token === '123456:invalidinvalidinvalidinvalid') throw Object.assign(new Error('secret-bearing upstream response'), { errorCode: 401 })
        return { id: token === tokenA ? 9001 : 9002, username: token === tokenA ? 'sample_bot' : 'replacement_bot' }
      },
      encrypt(value) { return `sealed:${value}` },
      platforms: () => ['telegram'],
      async publishChanged(ownerId) { published.push(ownerId) },
      dialect: 'postgres',
    })
    const app = createApp({
      appName: '合成测试应用',
      async isReady() { return true },
      userAuth: {
        secret,
        async lookupUser(id) {
          if (id !== ownerA && id !== ownerB) return null
          return {
            id, username: 'sample', displayName: '示例用户', email: 'sample@example.invalid', avatarUrl: null,
            createdAt: null, timezone: null, emailSubscribed: false, imChannels: [], isActive: true, securityVersion: 1,
          }
        },
      },
      telegramConnect: { connect: connector },
    })
    try {
      const authA = { authorization: `Bearer ${createUserToken(ownerA, 1, secret)}` }
      const authB = { authorization: `Bearer ${createUserToken(ownerB, 1, secret)}` }
      const denied = await app.inject({ method: 'POST', url: '/api/v1/me/telegram/connect', payload: { token: tokenA } })
      assert.equal(denied.statusCode, 401)
      assert.equal(verified.length, 0)

      const raced = await Promise.all([
        app.inject({ method: 'POST', url: '/api/v1/me/telegram/connect', headers: authA, payload: { token: tokenA } }),
        app.inject({ method: 'POST', url: '/api/v1/me/telegram/connect', headers: authB, payload: { token: tokenA } }),
      ])
      assert.deepEqual(raced.map(response => response.statusCode).sort(), [200, 409])
      const created = raced.find(response => response.statusCode === 200)!
      const createdOwner = created === raced[0] ? ownerA : ownerB
      const botId = created.json().id as number
      assert.equal(created.body.includes(tokenA), false)
      assert.equal((await pool.query('SELECT count(*)::int AS count FROM user_bots WHERE platform=$1 AND app_id=$2', ['telegram', '9001'])).rows[0]?.count, 1)
      assert.equal((await pool.query('SELECT app_secret FROM user_bots WHERE id=$1', [botId])).rows[0]?.app_secret, `sealed:${tokenA}`)
      assert.deepEqual(published, [createdOwner])
      assert.equal((await pool.query('SELECT context_epoch FROM conversation_sessions WHERE id=2')).rows[0]?.context_epoch, 4)
      assert.equal((await pool.query('SELECT context_epoch FROM conversation_sessions WHERE id=1')).rows[0]?.context_epoch, createdOwner === ownerA ? 3 : 2)
      assert.equal((await pool.query('SELECT context_epoch FROM conversation_sessions WHERE id=3')).rows[0]?.context_epoch, createdOwner === ownerB ? 8 : 7)

      const beforeForeignReplace = verified.length
      const foreignAuth = createdOwner === ownerA ? authB : authA
      const foreign = await app.inject({ method: 'PUT', url: `/api/v1/me/telegram/connect/${botId}`, headers: foreignAuth, payload: { token: tokenB } })
      assert.equal(foreign.statusCode, 404)
      assert.equal(verified.length, beforeForeignReplace)

      const ownerAuth = createdOwner === ownerA ? authA : authB
      await pool.query('UPDATE user_bots SET owner_platform_user_id=$1,owner_bound_at=CURRENT_TIMESTAMP WHERE id=$2', ['7001', botId])
      const replaced = await app.inject({ method: 'PUT', url: `/api/v1/me/telegram/connect/${botId}`, headers: ownerAuth, payload: { token: tokenB } })
      assert.equal(replaced.statusCode, 200)
      assert.deepEqual(replaced.json(), { id: botId, platform: 'telegram', name: '@replacement_bot', app_id: '9002', enabled: true })
      const replacement = (await pool.query('SELECT app_id,app_secret,owner_platform_user_id,owner_bound_at FROM user_bots WHERE id=$1', [botId])).rows[0]
      assert.deepEqual(replacement, { app_id: '9002', app_secret: `sealed:${tokenB}`, owner_platform_user_id: null, owner_bound_at: null })

      await pool.query('UPDATE user_bots SET owner_platform_user_id=$1,owner_bound_at=CURRENT_TIMESTAMP WHERE id=$2', ['7002', botId])
      const invalidToken = await app.inject({ method: 'PUT', url: `/api/v1/me/telegram/connect/${botId}`, headers: ownerAuth,
        payload: { token: '123456:invalidinvalidinvalidinvalid' } })
      assert.equal(invalidToken.statusCode, 400)
      assert.equal(invalidToken.body.includes('invalidinvalid'), false)
      const retained = (await pool.query('SELECT app_id,app_secret,owner_platform_user_id FROM user_bots WHERE id=$1', [botId])).rows[0]
      assert.deepEqual(retained, { app_id: '9002', app_secret: `sealed:${tokenB}`, owner_platform_user_id: '7002' })
      assert.deepEqual(published, [createdOwner, createdOwner])
    } finally {
      await app.close()
    }
  } finally {
    await runtime.close()
    await pool.end()
    await admin.query(`DROP SCHEMA "${schema}" CASCADE`)
    await admin.end()
  }
})
