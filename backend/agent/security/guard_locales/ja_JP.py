"""日本語 Guard ルール。"""

import re

from agent.security.guard_patterns import GuardLocale


JA_JP = GuardLocale(
    narration=re.compile(r"(?:読みました|確認しました|見つけました|変更しました|作成しました|保存しました|削除しました|送信しました|移動しました|完了しました|更新しました)"),
    action_request=re.compile(r"(?:並べ替え|並び替え|固定|アーカイブ|変更|名前変更|削除|追加|移動|整理|更新|編集)"),
    refusal=re.compile(r"(?:変更する必要はありません|並べ替える必要はありません|削除する必要はありません|追加する必要はありません|移動する必要はありません|変更しなくて|そのままで|すでに(?:問題ありません|完了しています|適切です))"),
    intent=re.compile(r"(?:これから|今から|すぐに|次に|確認します|調べます|作成します|変更します|削除します|移動します|更新します)"),
    question=re.compile(r"[?？]|(?:ですか|ますか|でしょうか|必要ですか)"),
    tool_progress_prefixes=("最新情報を検索しています", "確認しています", "調べてみます"),
    narration_nudge="【システム通知・ツールの結果がありません】操作を実行したと述べましたが、対応するツール呼び出しがありません。対応するツールを呼び出すか、実行できない理由を説明してください。",
    intent_nudge="【システム通知・宣言した操作が未実行です】操作を行うと述べましたが、ツール呼び出しがありません。今すぐツールを呼び出すか、不足している確認や情報を質問してください。",
    decision_nudge="【システム通知・明確な操作依頼の見落としを確認してください】引用履歴ではなく、今回のユーザー本文だけを判断してください。明確な実行依頼なら適切なツールを呼び出してください。案の相談、可否の質問、意図が不明な場合は通常どおり回答または確認し、相談を実行許可と解釈しないでください。",
    tool_required_nudge="前のターンは進捗だけで、実際のツール呼び出しがありません。適切なツールを呼び出すか、呼び出せない理由を明確に説明してください。",
    colon_nudge="前の返信はコロンで終わっており、内容が未完了の可能性があります。ユーザーへの回答を最後まで続けてください。依頼の完了にツールが必要なら呼び出し、不要なら説明を補ってください。断片を繰り返すだけにしないでください。",
)
