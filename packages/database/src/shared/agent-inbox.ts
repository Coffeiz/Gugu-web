/** 可信 Run 身份限定收件箱；正文只保留认证密文。 */
export function agentInboxSchema(binary: 'bytea' | 'BLOB') {
  const sequence = binary === 'bytea' ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT'
  return `
CREATE TABLE IF NOT EXISTS agent_inbox_messages (
  sequence ${sequence},
  owner_id TEXT NOT NULL,
  sender_session_id TEXT NOT NULL,
  sender_run_id TEXT NOT NULL,
  recipient_session_id TEXT NOT NULL,
  recipient_run_id TEXT NOT NULL,
  call_id TEXT NOT NULL,
  message_id TEXT NOT NULL UNIQUE,
  nonce ${binary} NOT NULL,
  payload ${binary} NOT NULL,
  consumed_checkpoint_version BIGINT,
  UNIQUE(owner_id,sender_session_id,sender_run_id,call_id)
);
CREATE INDEX IF NOT EXISTS agent_inbox_pending ON agent_inbox_messages(owner_id,recipient_session_id,recipient_run_id,sequence)
  WHERE consumed_checkpoint_version IS NULL;
CREATE TABLE IF NOT EXISTS agent_inbox_waits (
  owner_id TEXT NOT NULL,
  session_id TEXT NOT NULL,
  run_id TEXT NOT NULL,
  PRIMARY KEY(owner_id,session_id,run_id)
);
`
}
